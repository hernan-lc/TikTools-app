const dictionary: Record<Locale, Record<TranslationKey, string>> = {
  en: english,
  es: spanish,
};

export function t(locale: Locale, key: TranslationKey, values: Record<string, string | number> = {}): string {
  return dictionary[locale][key].replace(/\{(\w+)\}/g, (placeholder, name: string) => {
    const value = values[name];
    return value === undefined ? placeholder : String(value);
  });
}
